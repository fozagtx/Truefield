REQUIRED_CLOSEOUT = ["technician", "root_cause_confirmed", "actions_done", "loto_removed_by"]


class ReplayState:
    def __init__(self):
        self.running = False
        self.idx = 0
        self.start = 0
        self.speed = 1.0
        self.run_id = ""
        self.points: list[dict] = []
        self.consecutive = 0
        self.last_sev = "normal"
        self.naive_alarm_idx = None
        self.thread: threading.Thread | None = None
        self.stop_flag = threading.Event()


NO_LLM_ERROR = "MODEL_ACCESS_KEY is not set. Set it in .env (or MOCK=1 for tests only)."


def check_llm_configured(s: Settings) -> None:
    """Fail fast: never fall back to mock silently. Mock only with MOCK=1 / LLM_PROVIDER=mock."""
    mode = s.llm_mode
    if mode == "none" or (mode == "do" and not s.model_access_key):
        raise RuntimeError(NO_LLM_ERROR)
    if mode == "vllm" and not s.vllm_base_url:
        raise RuntimeError("LLM_PROVIDER=vllm but VLLM_BASE_URL is not set.")
    if mode == "evolus" and not (s.evolus_api_key and s.evolus_agent_model):
        raise RuntimeError("LLM_PROVIDER=evolus but EVOLUS_API_KEY / EVOLUS_APP_ID / EVOLUS_AGENT_ID are not set.")


class Truefield:
    def __init__(self, s: Settings):
        check_llm_configured(s)
        self.s = s
        self.store = Store(s.data_dir / "truefield.db")
        self.ec = EvolusClient(s, self.store)
        self.ds = load_dataset(s.data_dir, s.dataset)
        self.scorer = Scorer(self.ds, s.model_path)
        x = self.ds.signals[: max(8, int(self.ds.n * 0.4))].astype(np.float64)
        self.healthy_rms = float(np.mean(np.sqrt(np.mean((x - x.mean(axis=1, keepdims=True)) ** 2, axis=1))))
        self.replay = ReplayState()
        self._pipeline_lock = threading.Lock()
        self.bg_threads: list[threading.Thread] = []

    # ------------------------------------------------------------------ status
    def modes(self) -> dict:
        return {
            "llm": self.s.llm_mode + (" (cached)" if self.s.demo_cache else ""),
            "llm_model": {"do": self.s.model_name, "vllm": self.s.vllm_model, "evolus": self.s.evolus_agent_model}.get(self.s.llm_mode, "mock"),
            "evolus": self.ec.mode(),
            "workflow": self.ec.mode(self.s.evolus_workflow_id),
            "extractor": self.ec.mode(self.s.evolus_extractor_agent_id, self.s.evolus_extractor_id),
            "library": self.ec.mode(self.s.evolus_library_id),
            "voice_tool": self.ec.mode(),
            "anomaly_device": self.scorer.device_name,
            "model_trained_on_device": self.scorer.meta.get("device"),
            "data_source": self.ds.source,
            "data_badge": self.ds.badge,
        }

    # ------------------------------------------------------------------ replay
    def start_replay(self, speed: float = 1.0, start: int = 0, reset: bool = True):
        self.stop_replay()
        rp = self.replay
        if reset:
            rp.points = []
        rp.speed = max(0.1, float(speed))
        rp.start = int(max(0, min(start, self.ds.n - 1)))
        rp.idx = rp.start
        rp.consecutive = 0
        rp.last_sev = "normal"
        rp.naive_alarm_idx = None
        rp.run_id = uuid.uuid4().hex[:6]
        rp.stop_flag.clear()
        rp.running = True
        rp.thread = threading.Thread(target=self._replay_loop, daemon=True)
        rp.thread.start()
        self.store.audit("app", "replay.start", "", "", 200, 0, "local", f"speed={speed} start={start}")

    def stop_replay(self):
        rp = self.replay
        rp.stop_flag.set()
        if rp.thread and rp.thread.is_alive() and rp.thread is not threading.current_thread():
            rp.thread.join(timeout=5)
        rp.running = False

    def _rms_history(self, upto: int) -> list:
        t0 = self.ds.timestamps[0]
        lo = max(self.replay.start, upto - 30)
        return [((self.ds.timestamps[j] - t0).total_seconds() / 3600, self.scorer.score_index(j)["features"]["rms"]) for j in range(lo, upto + 1)]

    def step(self, i: int) -> dict:
        rp = self.replay
        rec = self.scorer.score_index(i)
        rp.consecutive = rp.consecutive + 1 if rec["above"] else 0
        rules = engine.evaluate(engine.RulesInput(
            z=rec["z"], ae_consecutive=rp.consecutive, temp_c=rec["temp_c"], temp_baseline_c=self.scorer.temp_baseline,
            rms_history=self._rms_history(i), asset=ASSETS[ASSET_ID]))
        naive = rec["features"]["rms"] >= 2 * self.healthy_rms
        if naive and rp.naive_alarm_idx is None:
            rp.naive_alarm_idx = i
        pt = {"idx": i, "ts": rec["ts"], "score": rec["score"], "threshold": rec["threshold"], "rms": rec["features"]["rms"],
              "kurtosis": rec["features"]["kurtosis"], "env_bpfo": rec["features"]["env_bpfo"], "z_env_bpfo": rec["z"]["env_bpfo"],
              "temp_c": rec["temp_c"], "severity": rules["severity"], "consecutive": rp.consecutive, "naive_alarm": naive}
        rp.points.append(pt)
        if engine.sev_rank(rules["severity"]) > engine.sev_rank(rp.last_sev) and engine.sev_rank(rules["severity"]) >= 1:
            rp.last_sev = rules["severity"]
            ev = self._make_event(rec, rules, rp.consecutive)
            self.store.add_event(ev)
            self.store.add_history(ASSET_ID, "anomaly", ev["event_id"], f"{rules['severity']} / {rules['fault_hypothesis']} at {rec['ts']} (data time)")
            if self.s.auto_pipeline:
                t = threading.Thread(target=self.auto_pipeline, args=(ev["event_id"],), daemon=True)
                self.bg_threads.append(t)
                t.start()
        return pt

    def _replay_loop(self):
        rp = self.replay
        try:
            for i in range(rp.start, self.ds.n):
                if rp.stop_flag.is_set():
                    break
                t0 = time.perf_counter()
                rp.idx = i
                self.step(i)
                dt = 1.0 / rp.speed - (time.perf_counter() - t0)
                if dt > 0 and rp.stop_flag.wait(dt):
                    break
        except Exception:
            log.exception("replay loop crashed")
        finally:
            rp.running = False

    def _make_event(self, rec, rules, consecutive) -> dict:
        rules_pub = {k: v for k, v in rules.items()}
        return {
            "event_id": f"EV-{self.replay.run_id}-{rec['idx']:04d}",
            "asset_id": ASSET_ID,
            "ts": rec["ts"],
            "created_at": now_iso(),
            "source": self.ds.source,
            "score": rec["score"],
            "threshold": rec["threshold"],
            "consecutive": consecutive,
            "model": {"name": "ae-v1", "device": self.scorer.device_name},
            "features": rec["features"],
            "z": rec["z"],
            "temp_c": rec["temp_c"],
            "temp_synthetic": True,
            "rules": rules_pub,
        }

    # ------------------------------------------------------------------ pipeline
    def auto_pipeline(self, event_id: str):
        try:
            ev = self.store.get_event(event_id)
            self.run_diagnosis(event_id)
            if engine.sev_rank(ev["rules"]["severity"]) >= engine.sev_rank("warning"):
                self.draft_work_order(event_id)
        except Exception:
            log.exception("auto pipeline failed for %s", event_id)

    def run_diagnosis(self, event_id: str, force: bool = False, question: str | None = None) -> dict:
        ev = self.store.get_event(event_id)
        if ev is None:
            raise KeyError(event_id)
        existing = self.store.get_diagnosis(event_id)
        if existing and not force and not question:
            return existing
        dx = diagnose(self.s, self.ec, ev, self.store, question)
        final, guard = engine.merge_invariants(ev["rules"], dx)
        dx["_final"] = final
        dx["_guardrails"] = guard
        for g in guard:
            self.store.metric("guardrail", 1, event_id, g)
            self.store.audit("app", "guardrail_triggered", "", "", None, 0, "local", g)
        if final["severity"] != ev["rules"]["severity"] or final["risk_level"] != ev["rules"]["risk_level"]:
            ev["rules"]["severity"], ev["rules"]["risk_level"] = final["severity"], final["risk_level"]
            ev["rules"]["priority"] = engine.load_rules()["priority"][final["severity"]]
            ev["rules"]["fired_rules"].append("LLM-ESCALATION")
            self.store.update_event(ev)
        self.store.put_diagnosis(event_id, dx)
        lat = (datetime.now(timezone.utc) - datetime.fromisoformat(ev["created_at"])).total_seconds()
        self.store.metric("alert_to_dx_s", lat, event_id)
        self.store.add_history(ev["asset_id"], "diagnosis", event_id, f"{dx['status']}: {dx['likely_cause']} (conf {dx['confidence']:.2f})")
        return dx

    def downtime_inputs(self) -> dict:
        planned, unplanned, cph = self.s.planned_minutes, self.s.unplanned_minutes, self.s.cost_per_hour_usd
        saved = unplanned - planned
        return {"planned_minutes": planned, "unplanned_baseline_minutes": unplanned, "minutes_saved": saved,
                "cost_per_hour_usd": cph, "cost_avoided_usd": round(saved / 60 * cph, 2),
                "assumptions": f"Illustrative: planned bearing swap {planned} min vs unplanned failure {unplanned} min; "
                               f"${cph:,.0f}/h = Siemens 2024 FMCG (lowest sector). cost_avoided = (unplanned - planned)/60 x cost_per_hour."}

    def deterministic_draft(self, ev: dict, dx: dict) -> dict:
        """§13.2 implemented in code: used as mock workflow output and as the last-resort fallback."""
        cite = {c["locator"]: c for c in dx.get("citations", [])}
        loto_loc = next((c["locator"] for c in dx.get("citations", []) if "loto" in c["doc"].lower()), None)
        first = next(iter(cite), None)
        steps = [{"text": "Apply lockout/tagout: complete every LOTO entry below and verify zero energy", "citation": loto_loc or "LOTO-PUMP-07"}]
        for a in dx.get("recommended_actions", []):
            if "loto" in a.lower() or "lockout" in a.lower():
                continue
            steps.append({"text": a, "citation": first})
        steps.append({"text": "Remove locks (only by the person who applied them) and record on close-out", "citation": loto_loc or "LOTO-PUMP-07"})
        return {"title": f"{dx.get('component', 'BRG-1')}: {dx.get('likely_cause', 'anomaly')} on {ev['asset_id']}",
                "steps": steps, "parts": dx.get("parts", []),
                "loto": [{"energy_source": x["energy_source"], "isolation_point": x["isolation_point"], "verify": x["verify"],
                          "citation": loto_loc or x["rule"]} for x in ev["rules"]["loto"]]}

    def _normalize_wo(self, raw: dict, ev: dict, dx: dict, source: str, exec_id: str | None, wo_id: str) -> dict:
        rules = ev["rules"]
        steps_in = raw.get("steps") or []
        steps = []
        for k, st in enumerate(steps_in, 1):
            if isinstance(st, str):
                st = {"text": st}
            steps.append({"n": k, "text": str(st.get("text", "")), "citation": st.get("citation") or None})
        # LOTO invariant: rules' required steps always present; LLM extras only if cited and well-formed.
        loto = [{"energy_source": x["energy_source"], "isolation_point": x["isolation_point"], "verify": x["verify"], "source": x["rule"]} for x in rules["loto"]]
        guard = []
        for x in raw.get("loto") or []:
            if isinstance(x, dict) and x.get("energy_source") in ("electrical", "mechanical", "hydraulic", "pneumatic", "thermal", "stored") \
                    and x.get("isolation_point") and x.get("verify") and x.get("citation"):
                if not any(x["isolation_point"] == y["isolation_point"] for y in loto):
                    loto.append({**{k: x[k] for k in ("energy_source", "isolation_point", "verify")}, "source": f"cited:{x['citation']}"})
        if raw.get("loto") is not None and len(raw.get("loto") or []) < len(rules["loto"]):
            guard.append("guardrail_triggered: drafted WO omitted rules LOTO steps; merged back deterministically")
        parts_ok = {p.get("part_no") for p in dx.get("parts", [])}
        parts = [p for p in (raw.get("parts") or []) if isinstance(p, dict) and p.get("part_no") in parts_ok]
        if len(parts) < len(raw.get("parts") or []):
            guard.append("guardrail_triggered: parts not in Diagnosis.parts dropped")
        wo = {
            "wo_id": wo_id, "event_id": ev["event_id"], "asset_id": ev["asset_id"],
            "status": "draft", "priority": rules["priority"],
            "severity": rules["severity"], "risk_level": rules["risk_level"],
            "title": raw.get("title") or f"{dx.get('component', 'BRG-1')}: {dx.get('likely_cause')} on {ev['asset_id']}",
            "steps": steps, "loto": loto, "parts": parts,
            "downtime_estimate": self.downtime_inputs(),
            "approval": {"required": False, "reasons": [], "by": None, "at": None, "decision": None},
            "evolus": {"workflow_execution_id": exec_id, "conversation_id": dx.get("_meta", {}).get("conversation_id")},
            "drafted_by": source, "safety_notice": SAFETY_FOOTER, "guardrails": guard, "log": [],
            "diagnosis_confidence": dx.get("confidence"), "diagnosis_status": dx.get("status"),
        }
        route, reasons = engine.route(rules, dx, wo)
        wo["route"] = route
        wo["approval"]["required"] = route == "supervisor"
        wo["approval"]["reasons"] = reasons
        wo["status"] = "pending_approval" if route == "supervisor" else "draft"
        errs = schema_errors("work_order", {k: v for k, v in wo.items()})
        if errs:
            raise ValueError(f"WorkOrder failed schema: {errs}")
        return wo

    def draft_work_order(self, event_id: str) -> dict:
        with self._pipeline_lock:
            existing = self.store.wo_for_event(event_id)
            if existing:
                return existing
            ev = self.store.get_event(event_id)
            if ev is None:
                raise KeyError(event_id)
            dx = self.store.get_diagnosis(event_id) or self.run_diagnosis(event_id)
            open_wo = self.store.open_wo_for_asset(ev["asset_id"])
            if open_wo:
                return self._escalate(open_wo, ev, dx)
            wo_id = self.store.next_wo_id()
        payload = {"event": ev, "rules": ev["rules"], "diagnosis": {k: v for k, v in dx.items() if not k.startswith("_")},
                   "downtime_inputs": self.downtime_inputs(), "wo_id": wo_id}
        input_text = json.dumps(payload, default=str)
        params = {"asset_id": ev["asset_id"], "route": ev["rules"]["route"]}  # no secrets in parameters
        callback = f"{self.s.public_base_url}/callback/evolus" if self.s.public_base_url else None
        raw, source, exec_id = None, None, None
        wf_status = self.ec.mode(self.s.evolus_workflow_id)
        try:
            exec_id = evwf.execute(self.ec, input_text, params, callback, mock_output=self.deterministic_draft(ev, dx))
            res = evwf.wait(self.ec, exec_id, self.store)
            raw = extract_json(evwf.output_text(res))
            source = "evolus_workflow" if not exec_id.startswith("mock-") else "mock_workflow"
        except (EvolusError, ValueError, KeyError) as e:
            log.warning("workflow path failed (%s); falling back to direct agent call", e)
            self.store.audit("app", "workflow.fallback", "", "", getattr(e, "status", None), 0, "local", str(e))
            try:
                msgs = [{"role": "system", "content": prompt("draft_wo")}, {"role": "user", "content": input_text}]
                res = chat(self.s, self.ec, msgs, "draft_wo", lambda _m: json.dumps(self.deterministic_draft(ev, dx)), self.store)
                raw = extract_json(res["content"])
                source = f"agent_direct:{res['provider']}"
            except Exception as e2:  # last resort: deterministic draft
                log.warning("agent drafting failed (%s); deterministic draft", e2)
                raw, source = self.deterministic_draft(ev, dx), "deterministic"
        if wf_status == "not configured":
            source = f"{source} (Evolus workflow not configured)"
        if isinstance(raw, dict) and "steps" not in raw and isinstance(raw.get("work_order"), dict):
            raw = raw["work_order"]
        try:
            wo = self._normalize_wo(raw if isinstance(raw, dict) else {}, ev, dx, source, exec_id, wo_id)
        except ValueError as e:
            log.warning("drafted WO invalid (%s); deterministic draft", e)
            wo = self._normalize_wo(self.deterministic_draft(ev, dx), ev, dx, "deterministic", exec_id, wo_id)
        for g in wo["guardrails"]:
            self.store.metric("guardrail", 1, wo_id, g)
        wo["log"].append({"at": now_iso(), "by": "truefield", "action": f"drafted ({source}); route={wo['route']}"})
        self.store.put_wo(wo)
        lat = (datetime.now(timezone.utc) - datetime.fromisoformat(ev["created_at"])).total_seconds()
        self.store.metric("time_to_wo_s", lat, wo_id)
        self.store.add_history(ev["asset_id"], "work_order", wo_id, f"{wo['title']} [{wo['priority']}, {wo['status']}]")
        return wo

    def _escalate(self, wo: dict, ev: dict, dx: dict) -> dict:
        rules = ev["rules"]
        if engine.sev_rank(rules["severity"]) > engine.sev_rank(wo.get("severity")):
            wo["severity"], wo["priority"] = rules["severity"], rules["priority"]
            have = {x["isolation_point"] for x in wo["loto"]}
            for x in rules["loto"]:
                if x["isolation_point"] not in have:
                    wo["loto"].append({"energy_source": x["energy_source"], "isolation_point": x["isolation_point"], "verify": x["verify"], "source": x["rule"]})
            route, reasons = engine.route(rules, dx, wo)
            if route == "supervisor" and wo["status"] in ("draft",):
                wo["status"] = "pending_approval"
                wo["approval"].update(required=True, reasons=reasons)
            wo["log"].append({"at": now_iso(), "by": "truefield", "action": f"escalated by {ev['event_id']} to {rules['severity']}"})
            wo.setdefault("related_events", []).append(ev["event_id"])
            self.store.put_wo(wo)
            self.store.add_history(ev["asset_id"], "work_order", wo["wo_id"], f"escalated to {rules['severity']} ({wo['priority']})")
        return wo

    # ------------------------------------------------------------------ approval
    def approve(self, wo_id: str, by: str, decision: str, edits: dict | None = None, note: str = "") -> dict:
        wo = self.store.get_wo(wo_id)
        if wo is None:
            raise KeyError(wo_id)
        if wo["status"] not in ("pending_approval", "draft"):
            raise ValueError(f"{wo_id} is {wo['status']}; nothing to approve")
        if decision not in ("approved", "edited", "rejected"):
            raise ValueError("decision must be approved|edited|rejected")
        if decision == "edited" and edits:
            for k in ("title", "steps", "parts", "priority"):
                if k in edits:
                    wo[k] = edits[k]
            # edits may add LOTO, never remove the rules' entries
            ev = self.store.get_event(wo["event_id"])
            must = {x["isolation_point"] for x in ev["rules"]["loto"]}
            new_loto = edits.get("loto")
            if new_loto is not None:
                kept = [x for x in wo["loto"] if x["isolation_point"] in must]
                extra = [x for x in new_loto if x.get("isolation_point") not in must]
                wo["loto"] = kept + extra
        wo["approval"].update(by=by, at=now_iso(), decision=decision)
        if decision == "rejected":
            wo["status"] = "rejected"
        else:
            if not wo["loto"]:
                raise ValueError("invariant: cannot issue a work order without LOTO steps")
            wo["status"] = "issued"
        wo["log"].append({"at": now_iso(), "by": by, "action": decision + (f": {note}" if note else "")})
        self.store.put_wo(wo)
        self.store.audit("app", f"wo.{decision}", "", wo_id, 200, 0, "local", f"by={by} note={note}")
        self.store.add_history(wo["asset_id"], "approval", wo_id, f"{decision} by {by}")
        return wo

    def issue(self, wo_id: str, by: str) -> dict:
        """Technician confirmation for auto_draft work orders (no supervisor needed)."""
        wo = self.store.get_wo(wo_id)
        if wo is None:
            raise KeyError(wo_id)
        if wo["status"] == "pending_approval":
            raise PermissionError("Awaiting supervisor: this work order cannot be issued without approval")
        if wo["status"] != "draft":
            raise ValueError(f"{wo_id} is {wo['status']}")
        if not wo["loto"]:
            raise ValueError("invariant: cannot issue a work order without LOTO steps")
        wo["status"] = "issued"
        wo["log"].append({"at": now_iso(), "by": by, "action": "confirmed and issued by technician"})
        self.store.put_wo(wo)
        self.store.add_history(wo["asset_id"], "approval", wo_id, f"issued by technician {by} (auto_draft)")
        return wo

    # ------------------------------------------------------------------ close-out
    def closeout(self, wo_id: str, source: str, filename: str, content: bytes, mime: str, overrides: dict | None = None) -> dict:
        t0 = time.perf_counter()
        wo = self.store.get_wo(wo_id)
        if wo is None:
            raise KeyError(wo_id)
        if wo["status"] not in ("issued", "in_progress"):
            raise PermissionError(f"{wo_id} is {wo['status']}; only issued work orders can be closed")
        if source not in ("photo", "pdf", "voice"):
            raise ValueError("source must be photo|pdf|voice")
        transcript = None
        evolus_status = "live"
        try:
            text = content.decode("utf-8") if filename.lower().endswith(".txt") else None
        except UnicodeDecodeError:
            text = None
        try:
            if source == "voice":
                res = evtools.run_media(self.ec, self.s.evolus_minutes_tool, content, filename, mime or "audio/mp4")
                transcript = res.get("sourceText") or res.get("transcript") or ""
                raw_ref = res.get("executionId") or res.get("id") or ("mock" if res.get("mock") else None)
            else:
                res = evx.ask_file(self.ec, content, filename, mime or ("application/pdf" if source == "pdf" else "image/jpeg"))
                fields = res.get("result") or {}
                raw_ref = (res.get("raw") or {}).get("id") if isinstance(res.get("raw"), dict) else ("mock" if res.get("mock") else None)
            if res.get("mock"):
                evolus_status = "mock"
        except EvolusNotConfigured:
            # No fake extraction: only a plain-text upload is read as-is; otherwise the technician fills the fields.
            evolus_status, raw_ref = "not configured", None
            if source == "voice":
                transcript = text or ""
            else:
                fields = evx.parse_form_text(text) if text else {}
        if source == "voice":
            fields = map_voice_transcript(self.s, self.ec, transcript, self.store) if transcript else {}
        fields = {k: v for k, v in fields.items() if v not in (None, "", [])}
        for k, v in (overrides or {}).items():
            if v not in (None, "", []):
                fields[k] = v
        co = {"wo_id": wo_id, "completed_at": now_iso(), "source": source, "raw_ref": str(raw_ref) if raw_ref else None, **fields}
        if isinstance(co.get("actions_done"), str):
            co["actions_done"] = [co["actions_done"]]
        missing = [k for k in REQUIRED_CLOSEOUT if not co.get(k)]
        errs = schema_errors("closeout", co) if not missing else []
        if missing or errs:
            note = " (Evolus not configured: extraction skipped, enter the fields manually)" if evolus_status == "not configured" else ""
            return {"closed": False, "missing": missing, "errors": errs, "draft": co, "transcript": transcript, "evolus": evolus_status,
                    "prompt": ("Please provide: " + ", ".join(missing) if missing else "Fix: " + "; ".join(errs)) + note}
        self.store.put_closeout(wo_id, co)
        wo["status"] = "closed"
        wo["closeout"] = co
        wo["log"].append({"at": now_iso(), "by": co["technician"], "action": f"closed via {source}"})
        self.store.put_wo(wo)
        self.store.metric("closeout_s", time.perf_counter() - t0, wo_id)
        self.store.add_history(wo["asset_id"], "closeout", wo_id, f"closed by {co['technician']}: {co['root_cause_confirmed']}; locks removed by {co['loto_removed_by']}")
        doc = self._wo_markdown(wo, co)
        learned = self.s.data_dir / "kb_learned"
        learned.mkdir(parents=True, exist_ok=True)
        (learned / f"{wo_id}.md").write_text(doc, encoding="utf-8")
        try:
            lib = evlib.upload_document(self.ec, f"{wo_id}.md", doc.encode("utf-8"))  # FR-9 feedback into the library
        except EvolusNotConfigured:
            lib = {"status": "Evolus not configured", "local_copy": f"kb_learned/{wo_id}.md"}
        except EvolusError as e:
            lib = {"status": f"upload failed: {e}"}
        return {"closed": True, "closeout": co, "transcript": transcript, "library": lib, "evolus": evolus_status, "wo": wo}

    @staticmethod
    def _wo_markdown(wo: dict, co: dict) -> str:
        parts = ", ".join(f"{p['part_no']} x{p.get('qty', 1)}" for p in co.get("parts_used", []) or []) or "none"
        return (f"# {wo['wo_id']} {wo['asset_id']}: {wo['title']}\n\n"
                f"- Closed: {co['completed_at']} by {co['technician']} (source: {co['source']})\n"
                f"- Root cause confirmed: {co['root_cause_confirmed']}\n"
                f"- Matches diagnosis: {co.get('matches_diagnosis')}\n"
                f"- Work done: {'; '.join(co['actions_done'])}\n- Parts: {parts}\n"
                f"- Actual downtime minutes: {co.get('actual_downtime_minutes')}\n"
                f"- LOTO removed by: {co['loto_removed_by']}\n- Follow-up: {co.get('follow_up')}\n")
